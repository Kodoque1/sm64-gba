#!/usr/bin/env python3
"""Lookup tables for the demo renderer (stored in cartridge ROM).

  gSinQ14[4096]       sin(2*pi*i/4096) * 16384, for angles >> 4
  gRecipZ[16384]      2^24 / z   (projection; z = 0 maps to 2^24)
  gRecipDy[2048]      2^24 / dy  (edge slopes; dy in 1/16 pixel units)
  gRecipClip[32768]   2^30 / d   (clip interpolation factors)
"""
import math
import sys


def emit(f, ctype, name, values, per_line=12):
    f.write(f"const {ctype} {name}[{len(values)}] = {{\n")
    for i in range(0, len(values), per_line):
        f.write("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",\n")
    f.write("};\n\n")


def main():
    out = sys.argv[1]
    sin_q14 = [int(round(math.sin(2 * math.pi * i / 4096) * 16384)) for i in range(4096)]
    recip_z = [1 << 24] + [int(round((1 << 24) / z)) for z in range(1, 16384)]
    recip_dy = [1 << 24] + [int(round((1 << 24) / d)) for d in range(1, 2048)]
    recip_clip = [1 << 30] + [int(round((1 << 30) / d)) for d in range(1, 32768)]
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_render_tables.py */\n\n")
        emit(f, "short", "gSinQ14", sin_q14)
        emit(f, "unsigned int", "gRecipZ", recip_z, 8)
        emit(f, "unsigned int", "gRecipDy", recip_dy, 8)
        emit(f, "unsigned int", "gRecipClip", recip_clip, 8)


if __name__ == "__main__":
    main()
