#!/usr/bin/env python3
"""Extract the animated-part hierarchy of Mario's body from the decomp's
actors/mario/geo.inc.c, in the order the renderer consumes animation channels.

Walks mario_geo_body the way geo_process_node does: GEO_BRANCH is inlined,
a GEO_SWITCH_CASE renders one child (case 0 here: all hand variants share
the same offset), every GEO_ANIMATED_PART consumes 3 channels (the first one
consumes the root translation too). Other nodes (rotation/scale/ASM/display
lists) carry no animation and identity or cosmetic transforms, so they are
pass-through for the skeleton.

Output: a C table { parent, x, y, z } per part (model units).
"""
import re
import sys


def parse_layouts(src):
    layouts = {}
    for m in re.finditer(r"const GeoLayout (\w+)\[\] = \{(.*?)\n\};", src, re.S):
        cmds = re.findall(r"(GEO_\w+)\(([^)]*)\)", m.group(2))
        layouts[m.group(1)] = [(c, [a.strip() for a in args.split(",")] if args.strip() else []) for c, args in cmds]
    return layouts


def build_tree(layouts, name):
    """Return a list of nodes: (cmd, args, children) for the layout, branches inlined."""
    cmds = layouts[name]
    pos = 0

    def parse_level():
        nonlocal pos
        nodes = []
        while pos < len(cmds):
            cmd, args = cmds[pos]
            if cmd == "GEO_CLOSE_NODE":
                pos += 1
                return nodes
            if cmd in ("GEO_RETURN", "GEO_END"):
                pos += 1
                continue
            if cmd == "GEO_OPEN_NODE":
                pos += 1
                children = parse_level()
                if nodes:
                    nodes[-1][2].extend(children)
                continue
            pos += 1
            if cmd == "GEO_BRANCH":
                nodes.extend(build_tree(layouts, args[1]))
            else:
                nodes.append((cmd, args, []))
        return nodes

    return parse_level()


def walk(nodes, parent, parts):
    for cmd, args, children in nodes:
        if cmd == "GEO_ANIMATED_PART":
            idx = len(parts)
            parts.append((parent, int(args[1]), int(args[2]), int(args[3])))
            walk(children, idx, parts)
        elif cmd == "GEO_SWITCH_CASE":
            if children:
                walk([children[0]], parent, parts)
        else:
            walk(children, parent, parts)


def main():
    geo, out = sys.argv[1], sys.argv[2]
    layouts = parse_layouts(open(geo).read())
    parts = []
    walk(build_tree(layouts, "mario_geo_body"), -1, parts)
    if len(parts) != 20:
        sys.exit(f"expected 20 animated parts, found {len(parts)}")
    with open(out, "w") as f:
        f.write("/* Generated by tools/gen_skeleton.py from actors/mario/geo.inc.c (mario_geo_body) */\n")
        f.write("const signed char gSkelParent[20] = {" + ", ".join(str(p[0]) for p in parts) + "};\n")
        f.write("const short gSkelOffset[20][3] = {\n")
        for p in parts:
            f.write(f"    {{ {p[1]}, {p[2]}, {p[3]} }},\n")
        f.write("};\n")
    for i, p in enumerate(parts):
        print(f"part {i:2d}: parent {p[0]:2d} offset {p[1:]}")


if __name__ == "__main__":
    main()
